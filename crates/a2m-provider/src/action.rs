//! An action a provider adds to the catalog, under its own name space.

use std::fmt;

use a2m_core::{Failure, Redact, Values};
use a2m_files::JsonSchema;

use crate::BoxFuture;
use crate::name::ActionName;
use crate::path::Roots;
use crate::registry::Registry;

/// What an action is given: checked paths and the registry, never the
/// store.
pub struct ActionContext<'a> {
    /// The roots the provider's manifest declares.
    pub roots: &'a Roots,
    /// The registry, to look up what is registered.
    pub registry: &'a Registry,
    /// The redactor.
    pub redact: &'a dyn Redact,
}

impl fmt::Debug for ActionContext<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ActionContext").finish_non_exhaustive()
    }
}

/// An action a provider adds. Its faces are generated by `a2m-actions`,
/// whose dispatcher alone calls it, after the caller's credential is checked
/// and policy has decided. A public contract.
pub trait ProviderAction: Send + Sync {
    /// The action's name, as the manifest declares it.
    fn name(&self) -> ActionName;
    /// The shape of its input.
    fn input_schema(&self) -> &JsonSchema;
    /// The shape of its output.
    fn output_schema(&self) -> &JsonSchema;
    /// Carries the action out.
    fn handle<'a>(
        &'a self,
        input: &'a Values,
        cx: &'a ActionContext<'a>,
    ) -> BoxFuture<'a, Result<Values, Failure>>;
}
