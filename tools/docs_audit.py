#!/usr/bin/env python3
"""Check the documentation set for broken links and contradictions, and the crates against it.

Usage, from the repository root:

    python3 tools/docs_audit.py                 # check; exit 1 on any finding
    python3 tools/docs_audit.py --write-sources # also regenerate docs/reference/sources.md
    python3 tools/docs_audit.py --root DIR      # check another copy of the repository

Standard library only; Python 3.11 or newer. Run it after any change under docs/, AGENTS.md,
README.md, or any crate's Cargo.toml. tools/test_docs_audit.py proves it fails when it should.
"""
import re
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

repo = (Path(sys.argv[sys.argv.index("--root") + 1]).resolve() if "--root" in sys.argv
        else Path(__file__).resolve().parent.parent)
docs = repo / "docs"
LINK = re.compile(r"\[([^\]]+)\]\((<[^>]+>|[^()\s]+(?:\([^()\s]*\)[^()\s]*)*)\)")


# Folders that hold what a build or an install produced, never a document of ours.
NOT_OURS = (".git/", "target/", "node_modules/", ".venv/", "venv/", "site-packages/")


def load():
    return {p.relative_to(repo).as_posix(): p.read_text(encoding="utf-8")
            for p in sorted(repo.rglob("*.md")) if not any(part in p.as_posix() for part in NOT_OURS)}


def links(text):
    return [(label, target.strip("<>")) for label, target in LINK.findall(text)]


def internal_dependencies(manifest, kinds=("dependencies", "dev-dependencies", "build-dependencies")):
    """Names of every package a crate manifest depends on, in the given dependency tables."""
    tables = [manifest] + list(manifest.get("target", {}).values())
    names = set()
    for table in tables:
        for kind in kinds:
            for key, spec in table.get(kind, {}).items():
                names.add(spec.get("package", key) if isinstance(spec, dict) else key)
    return names


def write_sources(md):
    by_file, urls = {}, set()
    for k, v in md.items():
        if k == "docs/reference/sources.md":
            continue
        seen = []
        for label, target in links(v):
            if target.startswith("http") and target not in [t for _, t in seen]:
                seen.append((label.strip("`*"), target))
                urls.add(target)
        if seen:
            by_file[k] = seen
    out = ["# Sources", "",
           f"Every external URL cited in these documents, grouped by the document that cites it: {len(urls)} distinct "
           f"URLs across {len(by_file)} documents. Generated by `tools/docs_audit.py --write-sources`.", "",
           "Where a research note says a finding is from a secondary source, a community post, or a vendor's own "
           "benchmark, that caveat applies to the link here too. See [research/README.md](../research/README.md).", ""]
    for k, items in by_file.items():
        out += [f"## {k}", ""]
        out += [f"- [{label}](<{t}>)" if "(" in t else f"- [{label}]({t})" for label, t in items]
        out.append("")
    (docs / "reference" / "sources.md").write_text("\n".join(out), encoding="utf-8")
    print(f"sources.md: {len(urls)} URLs from {len(by_file)} documents")


def main():
    md = load()
    if "--write-sources" in sys.argv:
        write_sources(md)
        md = load()
    found = defaultdict(list)

    def note(kind, msg):
        found[kind].append(msg)

    # 1. Relative links resolve.
    for k, v in md.items():
        for _, target in links(v):
            if target.startswith(("http", "#", "mailto:")):
                continue
            if not (repo / k).parent.joinpath(target.split("#")[0]).resolve().exists():
                note("links", f"{k}: broken link to {target}")

    spec = {k: v for k, v in md.items() if re.match(r"docs/spec/\d-[a-z-]+/\d{3}-", k)}
    ref = md["docs/reference/technical-reference.md"]
    catalog = md["docs/reference/action-catalog.md"]
    schema = md["docs/reference/ledger-schema.md"]

    # 2. Spec numbering and index.
    #    A section is docs/spec/<part>-<name>/<number>-<name>.md; its number has three digits and
    #    begins with its part's digit. Nothing else may sit in docs/spec/ but the index.
    index = md["docs/spec/README.md"]
    nums = []
    for k, v in spec.items():
        n = int(Path(k).name[:3])
        if n in nums:
            note("structure", f"{k}: section number {n} is used twice")
        nums.append(n)
        if not v.startswith(f"# {n}. "):
            note("structure", f"{k}: heading does not match its number")
        if str(n)[0] != Path(k).parent.name[0]:
            note("structure", f"{k}: section {n} is not in the part its first digit names")
        if Path(k).name not in index:
            note("structure", f"{k}: missing from docs/spec/README.md")
    for k in md:
        if k.startswith("docs/spec/") and k not in spec and k != "docs/spec/README.md":
            note("structure", f"{k}: not a section; a section is docs/spec/<part>/<number>-<name>.md")
    history = ("docs/decisions/", "docs/journal/", "docs/archive/")

    # 3. Built-in tools are actions in the catalog.
    actions = set(re.findall(r"`([a-z]+\.[a-z_]+)`", catalog))
    for k, v in md.items():
        for t in set(re.findall(r"\ba2m_[a-z]+(?:_[a-z]+)*\b", v)):
            parts = t.split("_")[1:]
            if len(parts) < 2:
                note("naming", f"{k}: {t} is not in noun_verb form")
            elif f"{parts[0]}.{'_'.join(parts[1:])}" not in actions:
                note("naming", f"{k}: {t} has no action in the catalog")

    # 4. Crates: spec 29 layout and the layering table agree; nothing else is named.
    layout = set(re.findall(r"\b(a2m-[a-z-]+)/", md["docs/spec/6-running-it/605-packaging-and-release.md"]))
    layer_text = ref[ref.index("## Crate layering"):ref.index("## Driver interface")]
    layering = set(re.findall(r"`(a2m-[a-z-]+)`", layer_text))
    for c in sorted(layout ^ layering):
        note("crates", f"{c} is in only one of the layout in spec section 605 and the layering table")
    for k, v in md.items():
        for c in set(re.findall(r"`(a2m-[a-z]+(?:-[a-z]+)*)`", v)) - layout:
            note("crates", f"{k}: {c} is not in the layout in spec section 605")

    # 5. Failure classes agree between the engine section and the reference.
    s08 = md["docs/spec/2-kernel/207-the-engine-loop.md"]
    c08 = set(re.findall(r"^\| `([a-z_]+)` \|", s08[s08.index("| Class | Example | Response |"):], re.M))
    codes = ref[ref.index("## Failure codes"):ref.index("## Command line")]
    cref = set(re.findall(r"^\| `([a-z_]+)` \|", codes, re.M))
    for c in sorted(c08 ^ cref):
        note("failures", f"class `{c}` is in only one of spec section 207 and the reference")

    # 6. States agree.
    s42 = md["docs/spec/2-kernel/208-runs-the-ledger-and-resume.md"]
    s44 = md["docs/spec/2-kernel/215-sessions-and-the-session-keeper.md"]
    s21 = md["docs/spec/2-kernel/221-the-tool-surface-agents-see.md"]

    def states(text, start, end):
        return re.findall(r"^\| `([a-z_]+)` \|", text[text.index(start):text.index(end)], re.M)

    for st in states(s42, "## Run states", "## Record states"):
        if f"`{st}`" not in s21:
            note("states", f"run state `{st}` is missing from the status list in spec section 221")
    for st in states(s42, "## Record states", "## Rules that must"):
        if f"`{st}`" not in schema:
            note("states", f"record state `{st}` is missing from the ledger schema")
    for st in states(s44, "## States", "## Three clocks"):
        if f"`{st}`" not in schema:
            note("states", f"session state `{st}` is missing from the ledger schema")

    # 7. Commands: single words are shortcuts, process commands, or nouns; noun-verb pairs are catalog actions.
    cmd = ref[ref.index("## Command line"):ref.index("### Command output contract")]
    known = set(re.findall(r"`([a-z]+)`", cmd))
    nouns = {a.split(".")[0] for a in actions}
    row = re.search(r"^\| Shortcuts \|(.+)$", cmd, re.M)
    shortcuts = set(re.findall(r"`([a-z]+)`", row.group(1))) if row else set()
    for k, v in md.items():
        for code in re.findall(r"`anything2mcp ([a-z]+(?: [a-z]+)?)[^`]*`", v):
            words = code.split()
            if words[0] not in known:
                note("commands", f"{k}: `anything2mcp {words[0]}` is not a shortcut, process command, or noun")
            elif len(words) == 2 and words[0] in nouns and words[0] not in shortcuts and f"{words[0]}.{words[1]}" not in actions:
                note("commands", f"{k}: `anything2mcp {code}` has no action `{words[0]}.{words[1]}`")

    # 8. Statements that later decisions replaced. Decision records and research notes may quote them.
    replaced = {
        r"attach(es|ing)? to (a|their|the user's) (running )?browser": "the engine does not attach to the user's browser (decision 0031)",
        r"started by the MCP client over stdio": "one engine per user, not one per MCP client (decision 0024)",
        r"optional in-process bindings": "in-process bindings are deferred (decision 0025)",
        r"browser context(s)? seeded": "runs share a live session in tabs (decision 0032)",
        r"input hash, and approval": "a run is identified by caller, tool version, and input hash (spec 42, rule 6)",
        r"marked interrupted": "a crashed run is `stopped`; interrupted is not a run state (spec 42)",
        r"confirmed actions in a UI binding": "commit points are actions marked `commits` (file formats)",
        r"[Ee]ngine steps": "the engine loop has parts; a step is one driver instruction (glossary)",
    }
    for pat, why in replaced.items():
        for k, v in md.items():
            if k.startswith(history + ("docs/research/", "docs/spec/7-project/704-")):
                continue
            for i, line in enumerate(v.splitlines(), 1):
                if re.search(pat, line) and "withdrawn" not in line and "arlier" not in line:
                    note("replaced", f"{k}:{i}: {why}")

    # 9. References to sections, phases, and research briefs exist.
    briefs = set(int(n) for n in re.findall(r"^\| (\d+) \|", md["docs/research/11-open-research.md"], re.M))
    texts = set(int(n) for n in re.findall(r"^\*\*(\d+)\. ", md["docs/research/11-open-research.md"], re.M))
    if briefs != texts:
        note("research", f"brief table and brief texts differ: {sorted(briefs ^ texts)}")
    for k, v in md.items():
        for m in re.finditer(r"\b[Ss]ections? (\d+)", v):
            if int(m.group(1)) not in nums and not k.startswith(history):
                note("refs", f"{k}: section {m.group(1)} does not exist")
        for m in re.finditer(r"\bPhase (\d+)", v):
            if int(m.group(1)) > 9:
                note("refs", f"{k}: Phase {m.group(1)} does not exist")
        for m in re.finditer(r"\bbriefs? (\d+)(?: and (\d+))?", v):
            for g in m.groups():
                if g and int(g) not in briefs:
                    note("refs", f"{k}: research brief {g} does not exist")

    # 10. Counts in the indexes are true.
    n_dec = len([k for k in md if re.match(r"docs/decisions/\d", k)])
    n_res = len([k for k in md if re.match(r"docs/research/\d", k)])
    dr = md["docs/README.md"]
    for label, n, pat in (("spec sections", len(nums), r"\| (\d+) sections \|"),
                          ("decisions", n_dec, r"alternatives[^|]*\| (\d+) \|"),
                          ("research files", n_res, r"briefs still to run \| (\d+) \|")):
        m = re.search(pat, dr)
        if not m or int(m.group(1)) != n:
            note("counts", f"docs/README.md gives {m.group(1) if m else 'no number'} for {label}; there are {n}")
    m = re.search(r"\| (\d+) research briefs still to run", md["docs/research/README.md"])
    if not m or int(m.group(1)) != len(briefs):
        note("counts", f"docs/research/README.md gives {m.group(1) if m else 'no number'} briefs; there are {len(briefs)}")
    for k in md:
        if re.match(r"docs/research/\d", k) and Path(k).name not in md["docs/research/README.md"]:
            note("counts", f"{k} is not listed in docs/research/README.md")
        if re.match(r"docs/decisions/\d", k) and Path(k).name not in md["docs/decisions/README.md"]:
            note("counts", f"{k} is not listed in docs/decisions/README.md")

    # 11. The sets that must never change size by accident.
    for k, v in md.items():
        if re.search(r"\b(six|eight|five) (modes|drivers)\b", v):
            note("sets", f"{k}: a mode count other than seven")
        if re.search(r"\b(three|five) identity modes\b", v):
            note("sets", f"{k}: an identity-mode count other than four")

    # 12. Skills, journal, and hypotheses are well formed and indexed.
    for k, v in md.items():
        if k.startswith(".claude/skills/") and k.endswith("SKILL.md"):
            head = v.split("---")
            if not v.startswith("---") or len(head) < 3 or "name:" not in head[1] or "description:" not in head[1]:
                note("skills", f"{k}: needs frontmatter with name and description on the first lines")
            m = re.search(r"^name: (.+)$", head[1] if len(head) > 1 else "", re.M)
            if m and m.group(1).strip() != Path(k).parent.name:
                note("skills", f"{k}: name does not match its folder")
    journal = md.get("docs/journal/README.md", "")
    for k in md:
        if re.match(r"docs/journal/\d{4}-", k) and Path(k).name not in journal:
            note("journal", f"{k} is not listed in docs/journal/README.md")
    register = md.get("docs/hypotheses/README.md", "")
    ids = re.findall(r"^\| (H-\d+) \|", register, re.M)
    if len(ids) != len(set(ids)):
        note("hypotheses", "a hypothesis number is used twice in the register")
    for row in re.findall(r"^\| (H-\d+) \|.*\| ([a-z]+) \|$", register, re.M):
        if row[1] not in ("open", "supported", "refuted", "changed"):
            note("hypotheses", f"{row[0]} has an unknown status: {row[1]}")
        if row[1] != "open" and not any(k.startswith(f"docs/hypotheses/{row[0]}-") for k in md):
            note("hypotheses", f"{row[0]} is marked {row[1]} but has no result file")
    for k, v in md.items():
        for h in set(re.findall(r"\bH-(\d+)\b", v)):
            if f"H-{h}" not in ids and h != "00" and h != "NN":
                note("hypotheses", f"{k}: refers to H-{h}, which is not in the register")

    # 13. Crates on disk match the layering table, and depend only on what their row allows.
    #     A kernel crate never depends on a pack crate; a pack crate depends on the kernel's
    #     lower layers and on the base of its own pack, and on nothing else (decision 0056).
    layer, reach = {}, {}
    for m in re.finditer(r"^\| (\d+)\. [^|]+\|([^|]+)\|([^|]+)\|", layer_text, re.M):
        number, allowed = int(m.group(1)), m.group(3)
        top = re.search(r"Layers? (?:1 to )?(\d+)", allowed)
        reach[number] = number - 1 if "Everything" in allowed else int(top.group(1)) if top else 0
        for c in re.findall(r"`([a-z0-9-]+)`", m.group(2)):
            layer[c] = number

    def pack_of(crate):
        return crate.split("-")[2] if crate.startswith("a2m-pack-") else None

    # Every crate under targets/ is test equipment, the test application and each test stand alike.
    stands = set()
    for manifest_path in sorted((repo / "targets").glob("*/Cargo.toml")):
        try:
            stand = tomllib.loads(manifest_path.read_text(encoding="utf-8")).get("package", {}).get("name")
        except tomllib.TOMLDecodeError as e:
            note("layering", f"targets/{manifest_path.parent.name}/Cargo.toml cannot be parsed: {e}")
            continue
        if stand:
            stands.add(stand)

    on_disk = {}
    crates_dir = repo / "crates"
    for manifest_path in sorted(crates_dir.glob("*/Cargo.toml")) if crates_dir.is_dir() else []:
        folder = manifest_path.parent.name
        try:
            manifest = tomllib.loads(manifest_path.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError as e:
            note("layering", f"crates/{folder}/Cargo.toml cannot be parsed: {e}")
            continue
        name = manifest.get("package", {}).get("name")
        if name != folder:
            note("layering", f"crates/{folder} holds a package named {name}; the two must match")
        on_disk[folder] = internal_dependencies(manifest)
        for stand in sorted(stands & internal_dependencies(manifest, ("dependencies", "build-dependencies"))):
            note("layering", f"{folder} depends on {stand} outside its tests; "
                             "a crate under targets/ is test equipment and may only be a dev-dependency")
    if crates_dir.is_dir():
        for c in sorted(set(on_disk) - set(layer)):
            note("layering", f"crates/{c} exists but is not in the layering table of the technical reference")
        for c in sorted(set(layer) - set(on_disk)):
            note("layering", f"{c} is in the layering table but crates/{c} does not exist")
    # Edges the layers would allow and the design forbids (docs/architecture/README.md).
    forbidden = {
        ("a2m-engine", "a2m-files"): "the engine runs only compiled plans and never depends on the compiler "
                                     "(decision 0036)",
        ("a2m-engine", "a2m-policy"): "only the control plane decides; the engine asks through Control",
    }
    for c, deps in sorted(on_disk.items()):
        for d in sorted(deps):
            if (c, d) in forbidden:
                note("layering", f"{c} depends on {d}; {forbidden[(c, d)]}")
                continue
            if d not in layer:
                if d.startswith("a2m-") or d == "anything2mcp":
                    note("layering", f"{c} depends on {d}, which is not in the layering table")
                continue
            if c not in layer or layer[d] <= reach[layer[c]]:
                continue
            edge = f"{c} (layer {layer[c]}) depends on {d} (layer {layer[d]})"
            if pack_of(d) and not pack_of(c) and c != "anything2mcp":
                note("layering", f"{edge}; a kernel crate never depends on a pack crate")
            elif pack_of(d) and pack_of(c):
                if pack_of(d) != pack_of(c) or layer[d] >= layer[c]:
                    note("layering", f"{edge}; a pack crate may depend on another pack crate "
                                     "only when that crate is the base of its own pack")
            else:
                note("layering", f"{edge}; its row in the layering table allows layers 1 to {reach[layer[c]]}")

    # 14. One version number, and one licence text, wherever they are carried.
    workspace_file, pip_file = repo / "Cargo.toml", repo / "bindings" / "python" / "pyproject.toml"
    if workspace_file.is_file() and pip_file.is_file():
        try:
            crate_version = tomllib.loads(workspace_file.read_text(encoding="utf-8"))["workspace"]["package"]["version"]
            pip_version = tomllib.loads(pip_file.read_text(encoding="utf-8"))["project"]["version"]
            if crate_version != pip_version:
                note("release", f"the workspace is version {crate_version} and the pip package is {pip_version}; "
                                "every package carries the same version")
        except (tomllib.TOMLDecodeError, KeyError) as e:
            note("release", f"cannot read a version from Cargo.toml or bindings/python/pyproject.toml: {e!r}")
        licence, copy = repo / "LICENSE", pip_file.parent / "LICENSE"
        if not copy.is_file() or not licence.is_file() or copy.read_bytes() != licence.read_bytes():
            note("release", "bindings/python/LICENSE must be an exact copy of LICENSE")

    # 15. The product's earlier names appear only in history (decision 0056).
    earlier = re.compile(r"Web2MCP|web2mcp|w2mcp|\bw2m[-_]|\bW2M_")
    history = ("docs/decisions/", "docs/journal/", "docs/archive/", "docs/plan/publishing-setup.md",
               "docs/research/10-", "docs/research/12-",
               "docs/reference/sources.md",
               "CHANGELOG.md", "tools/docs_audit.py", "tools/test_docs_audit.py")
    kinds = {".md", ".rs", ".toml", ".lock", ".yml", ".yaml", ".py", ".json", ".txt", ".cfg", ".sh", ".ps1"}
    skipped = {".git", "target", "__pycache__", "dist", ".venv", "venv", "node_modules", "site-packages"}
    for path in sorted(repo.rglob("*")):
        rel = path.relative_to(repo).as_posix()
        if (not path.is_file() or skipped & set(rel.split("/")) or rel.startswith(history)
                or (path.suffix not in kinds and not path.name.startswith("."))):
            continue
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except UnicodeDecodeError:
            continue
        for i, line in enumerate(lines, 1):
            found_name = earlier.search(re.sub(r"\]\([^)]*decisions/[^)]*\)", "]", line))
            if found_name:
                note("names", f"{rel}:{i}: `{found_name.group(0)}` is an earlier name; "
                              "the product is Anything2MCP, its crates are a2m-*")

    # 16. Every crate has a design in docs/architecture/crates/, every design names a crate that
    #     exists, and each design states the layer the layering table gives (decision 0061).
    designs_dir = docs / "architecture" / "crates"
    if designs_dir.is_dir():
        designs = {f.stem: f.read_text(encoding="utf-8") for f in sorted(designs_dir.glob("*.md"))}
        for c in sorted(set(on_disk) - set(designs)):
            note("designs", f"crates/{c} has no design at docs/architecture/crates/{c}.md")
        for c in sorted(set(designs) - set(on_disk)):
            note("designs", f"docs/architecture/crates/{c}.md describes a crate that does not exist")
        for c, text in sorted(designs.items()):
            if not text.startswith(f"# `{c}`\n"):
                note("designs", f"docs/architecture/crates/{c}.md must begin with the heading # `{c}`")
            stated = re.search(r"^\| Layer \| (\d+)", text, re.M)
            if c in layer and (not stated or int(stated.group(1)) != layer[c]):
                note("designs", f"docs/architecture/crates/{c}.md must state layer {layer[c]} in its Facts table, "
                                f"as the layering table does")

    total = sum(len(v) for v in found.values())
    print(f"checked {len(md)} files: {len(nums)} spec sections, {n_dec} decisions, {n_res} research files, "
          f"{len(actions)} actions, {len(briefs)} open research briefs, {len(on_disk)} crates")
    for kind in found:
        print(f"\n[{kind}] {len(found[kind])}")
        for msg in found[kind]:
            print("  -", msg)
    print(f"\n{total} finding(s)")
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main())
