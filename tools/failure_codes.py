#!/usr/bin/env python3
"""Write, or check, the table of failure codes in docs/reference/technical-reference.md.

Usage, from the repository root:

    python3 tools/failure_codes.py                 # rewrite the table between the markers
    python3 tools/failure_codes.py --check         # exit 1 and name each difference if it is stale
    python3 tools/failure_codes.py --list          # print the table, and write nothing
    python3 tools/failure_codes.py --root DIR      # work on another copy of the repository

The crates hold the knowledge; this tool only reads it, as text, without a build. Every crate declares
its codes in one form (decision 0258): the rows of its `a2m_core::failure_codes! { NAME = Class,
"code", meaning "...", next "..." [, passes by_itself | not_by_itself] [, then ("noun.verb", "what
for")]; ... }` table, and, for a pack, also its manifest's `[[failure_codes]]` entries, which give a
class and may give a meaning. A code of another crate a pack passes on is in its manifest alone.

These are faults, which the tool names and for which it exits 1 in every mode: a code declared with
two classes; a row of the table form that cannot be read, or that has an empty meaning or next step;
one code given two answers to whether it passes by itself; and a code declared outside a table, as a
literal `FailureCode::fixed("code")` in a crate's source, so that no crate can slip back into an
older form. Lint codes (`kernel.*`) are another vocabulary and are not read.
Standard library only; Python 3.11 or newer.
"""
import re
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

repo = (Path(sys.argv[sys.argv.index("--root") + 1]).resolve() if "--root" in sys.argv
        else Path(__file__).resolve().parent.parent)
REFERENCE = "docs/reference/technical-reference.md"
BEGIN = "<!-- failure-codes:begin (generated by tools/failure_codes.py; do not edit by hand) -->"
END = "<!-- failure-codes:end -->"
CLASS_ORDER = ["policy", "input", "session_expired", "edge_blocked", "drift", "unknown_variant",
               "rejected", "mismatch", "possible_commit", "stale", "transient", "busy"]
CLASSES = set(CLASS_ORDER)
PASSES = {"by_itself": "yes", "not_by_itself": "no"}

CODE = r"[a-z][a-z0-9_]*"
INLINE = re.compile(rf'FailureCode::fixed\(\s*"({CODE})"\s*\)')
STR = r'"((?:[^"\\]|\\.)*)"'
FC_START = re.compile(r"^[^\n/]*?\bfailure_codes!\s*\{", re.M)
FC_ROW = re.compile(rf'\s*(\w+)\s*=\s*(\w+)\s*,\s*"({CODE})"\s*,\s*meaning\s*{STR}\s*,\s*next\s*{STR}'
                    rf'(?:\s*,\s*passes\s+(\w+))?(?:\s*,\s*then\s*\(\s*{STR}\s*,\s*{STR}\s*\))?\s*', re.S)
TEST_FILE = re.compile(r"(^|/)(tests|benches|examples|target)/|(^|/)(tests|test_\w+|\w+_tests)\.rs$")


def snake(name):
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def unescape(text):
    """The value of the inside of a plain Rust string literal."""
    text = re.sub(r"\\\n\s*", "", text)
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t", "0": "\0"}.get(m.group(1), m.group(1)), text)


def block_end(text, start):
    """The index of the brace that closes the block opened just before `start`, skipping strings
    and comments; -1 when it is not closed."""
    depth, i = 1, start
    while i < len(text):
        c = text[i]
        if c == '"':
            i += 1
            while i < len(text) and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif text.startswith("//", i):
            i = text.find("\n", i)
            if i < 0:
                return -1
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def split_rows(body):
    """The rows of a `failure_codes!` block: its text cut at each `;` outside a string, with line
    comments taken out."""
    rows, row, i = [], [], 0
    while i < len(body):
        c = body[i]
        if c == '"':
            j = i + 1
            while j < len(body) and body[j] != '"':
                j += 2 if body[j] == "\\" else 1
            row.append(body[i:j + 1])
            i = j + 1
            continue
        if body.startswith("//", i):
            j = body.find("\n", i)
            i = len(body) if j < 0 else j
            continue
        if c == ";":
            rows.append("".join(row))
            row = []
        else:
            row.append(c)
        i += 1
    rest = "".join(row)
    if rest.strip():
        rows.append(rest)
    return [r for r in rows if r.strip()]


def table_rows(text, rel, faults):
    """(rows, text with the blocks taken out): each row (code, class, meaning, next, passes, then)."""
    found, cuts = [], []
    for m in FC_START.finditer(text):
        end = block_end(text, m.end())
        if end < 0:
            faults.append(f"{rel}: a `failure_codes!` table is not closed")
            continue
        cuts.append((m.start(), end + 1))
        for row in split_rows(text[m.end():end]):
            r = FC_ROW.fullmatch(row)
            shown = re.sub(r"\s+", " ", row).strip()[:80]
            if not r:
                faults.append(f"{rel}: a row of `failure_codes!` cannot be read: `{shown}`; write it as "
                              'NAME = Class, "code", meaning "...", next "..." [, passes by_itself | not_by_itself] '
                              '[, then ("noun.verb", "what for")];')
                continue
            _name, cls, code, meaning, nxt, passes, then_action, then_when = r.groups()
            meaning, nxt = unescape(meaning).strip(), unescape(nxt).strip()
            cls = snake(cls)
            if cls not in CLASSES:
                faults.append(f"{rel}: `{code}` is given the class `{r.group(2)}`, which is not a failure class")
                continue
            if not meaning:
                faults.append(f"{rel}: `{code}` has an empty meaning in its `failure_codes!` row")
            if not nxt:
                faults.append(f"{rel}: `{code}` has an empty next step in its `failure_codes!` row")
            if passes is not None and passes not in PASSES:
                faults.append(f"{rel}: `{code}` says `passes {passes}`; write `passes by_itself` or `passes not_by_itself`")
                passes = None
            if cls == "busy" and passes is None:
                faults.append(f"{rel}: `{code}` is `busy` and does not say whether it passes by itself")
            if passes is None:
                passes = "by_itself" if cls == "transient" else "not_by_itself"
            then = (unescape(then_action), unescape(then_when)) if then_action is not None else None
            found.append((code, cls, meaning, nxt, passes, then))
    for a, b in reversed(cuts):
        text = text[:a] + text[b:]
    return found, text


class Found:
    def __init__(self):
        self.by_code = defaultdict(lambda: {"classes": defaultdict(set), "crates": set(), "meanings": {},
                                            "rows": {}})
        self.faults = []

    def add(self, crate, code, cls, how, meaning=None):
        row = self.by_code[code]
        row["crates"].add(crate)
        row["classes"][cls].add((crate, how))
        if meaning and crate not in row["meanings"]:
            row["meanings"][crate] = meaning


def source_files(crate_dir):
    for p in sorted(crate_dir.rglob("*.rs")):
        rel = p.relative_to(crate_dir).as_posix()
        if not TEST_FILE.search(rel):
            yield p


def read_rust(p):
    text = p.read_text(encoding="utf-8")
    cut = re.search(r"^#\[cfg\(test\)\]", text, re.M)
    return text[:cut.start()] if cut else text


def scan(root=repo):
    f = Found()
    crates_dir = root / "crates"
    for crate_dir in sorted(d for d in crates_dir.iterdir() if d.is_dir()):
        crate = crate_dir.name
        for toml in sorted(crate_dir.rglob("*.toml")):
            if "target" in toml.relative_to(crate_dir).parts or toml.name == "Cargo.toml":
                continue
            try:
                data = tomllib.loads(toml.read_text(encoding="utf-8"))
            except tomllib.TOMLDecodeError as e:
                f.faults.append(f"{toml.relative_to(root).as_posix()}: cannot be read as TOML: {e}")
                continue
            for entry in data.get("failure_codes", []):
                if entry.get("class") in CLASSES and re.fullmatch(CODE, str(entry.get("code", ""))):
                    f.add(crate, entry["code"], entry["class"], "manifest", entry.get("meaning"))
                else:
                    f.faults.append(f"{toml.relative_to(root).as_posix()}: a failure_codes entry has no valid class and code: {entry!r}")
        for p in source_files(crate_dir):
            rel = p.relative_to(root).as_posix()
            rows, rest = table_rows(read_rust(p), rel, f.faults)
            for code, cls, meaning, nxt, passes, then in rows:
                f.add(crate, code, cls, "macro", meaning)
                f.by_code[code]["rows"].setdefault(crate, (meaning, nxt, passes, then))
            # Outside a table, a code is named only by a constant of a table or a manifest's code.
            for m in INLINE.finditer(rest):
                f.faults.append(f"{rel}: `{m.group(1)}` is declared outside a `failure_codes!` table, as "
                                f"`FailureCode::fixed`; declare it in {crate}'s table and use the constant")
    return f


def layers(root):
    """Crate -> its layer number, from the layering table of the reference."""
    text = (root / REFERENCE).read_text(encoding="utf-8")
    start = text.find("## Crate layering")
    table = text[start:text.find("\n## ", start + 1)] if start >= 0 else ""
    found = {}
    for m in re.finditer(r"^\| (\d+)\. [^|]+\|([^|]+)\|", table, re.M):
        for crate in re.findall(r"`([a-z0-9-]+)`", m.group(2)):
            found[crate] = int(m.group(1))
    return found


def preference(root):
    """The order in which the crates that declare one code are shown, the first giving the row's
    meaning: the core, then the provider contract, then the other kernel crates by layer, lowest
    first, then the pack crates, bases and packs alike, then any crate the layering table does not
    name; by name within each. A pack base's wording is its own kind of system's, so it is not put
    before the packs'."""
    layer = layers(root)
    first = {"a2m-core": 0, "a2m-provider": 1}

    def key(crate):
        n = layer.get(crate)
        rank = 100 if n is None else 90 if crate.startswith("a2m-pack-") else n
        return (first.get(crate, 2), rank, crate)
    return key


def resolve(f, root=repo):
    """(rows, faults): rows are (class, code, crates, meaning), sorted by class then code."""
    prefer = preference(root)
    rows, faults = [], list(f.faults)
    for code, row in sorted(f.by_code.items()):
        classes = set(row["classes"])
        if len(classes) > 1:
            where = "; ".join(f"`{c}` in " + ", ".join(sorted({f'{cr} ({how})' for cr, how in row['classes'][c]})) for c in sorted(classes))
            faults.append(f"`{code}` is declared with more than one class: {where}")
            continue
        cls = next(iter(classes))
        answers = {passes for _, _, passes, _ in row["rows"].values()}
        if len(answers) > 1:
            where = "; ".join(f"`{passes}` in {crate}" for crate, (_, _, passes, _) in sorted(row["rows"].items()))
            faults.append(f"`{code}` is given two answers to whether it passes by itself: {where}")
        meaning, nxt, passes = "", "", ""
        if row["rows"]:
            meaning, nxt, passes, _ = row["rows"][sorted(row["rows"], key=prefer)[0]]
            passes = PASSES[passes]
        else:
            for crate in sorted(row["meanings"], key=prefer):
                meaning = row["meanings"][crate]
                break
        meaning = meaning[:1].upper() + meaning[1:]
        rows.append((cls, code, sorted(row["crates"], key=prefer), meaning, nxt, passes))
    rows.sort(key=lambda r: (CLASS_ORDER.index(r[0]), r[1]))
    return rows, faults


def cell(text):
    return text.replace("|", "\\|")


def render(rows):
    out = ["| Class | Code | Declared in | What it says | What to do | Passes by itself |",
           "| --- | --- | --- | --- | --- | --- |"]
    for cls, code, crates, meaning, nxt, passes in rows:
        out.append(f"| `{cls}` | `{code}` | {', '.join(f'`{c}`' for c in crates)} | {cell(meaning)} | {cell(nxt)} | {passes} |")
    return "\n".join(out)


def current_block(text):
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        return None
    return text[a + len(BEGIN):b].strip("\n")


def check(root):
    """Every way the reference's table differs from what the crates say, as sentences."""
    f = scan(root)
    rows, faults = resolve(f, root)
    text = (root / REFERENCE).read_text(encoding="utf-8")
    block = current_block(text)
    if block is None:
        return faults + [f"{REFERENCE}: the failure-codes markers are missing"]
    want = render(rows)
    have = {}
    for line in block.splitlines():
        m = re.match(r"\| `(\w+)` \| `(\w+)` \|", line)
        if m:
            have[m.group(2)] = line
    wanted = {r[1]: line for r, line in zip(rows, want.splitlines()[2:])}
    problems = list(faults)
    for code in sorted(set(wanted) - set(have)):
        problems.append(f"`{code}` is declared in {', '.join(next(r[2] for r in rows if r[1] == code))} "
                        "and has no row in the reference's table")
    for code in sorted(set(have) - set(wanted)):
        problems.append(f"the reference's table has a row for `{code}` and no crate declares it")
    for code in sorted(set(have) & set(wanted)):
        if have[code] != wanted[code]:
            problems.append(f"the row for `{code}` is not what the crates say; run `python3 tools/failure_codes.py`")
    if not problems and block != want:
        problems.append("the table differs from what the generator writes; run `python3 tools/failure_codes.py`")
    return problems


def main():
    f = scan()
    rows, faults = resolve(f)
    for fault in faults:
        print("fault:", fault)
    if "--list" in sys.argv:
        print(render(rows))
        return 1 if faults else 0
    path = repo / REFERENCE
    text = path.read_text(encoding="utf-8")
    block = current_block(text)
    if block is None:
        print(f"{REFERENCE}: the failure-codes markers are missing")
        return 1
    want = render(rows)
    if "--check" in sys.argv:
        problems = check(repo)
        for p in problems:
            print("-", p)
        print(f"{len(rows)} codes; {len(problems)} problem(s)")
        return 1 if problems else 0
    a = text.find(BEGIN) + len(BEGIN)
    new = text[:a] + "\n" + want + "\n" + text[text.find(END):]
    if new != text:
        path.write_text(new, encoding="utf-8")
    print(f"{REFERENCE}: {len(rows)} codes written" + (" (changed)" if new != text else " (unchanged)"))
    return 1 if faults else 0


if __name__ == "__main__":
    sys.exit(main())
